// Helper to generate dynamic location data if user clicks on arbitrary map coordinates
export function generateDynamicLocationForCoord(lat: number, lng: number): EnvLocation {
  const hash = Math.abs(Math.floor(Math.sin(lat * 12.9898 + lng * 78.233) * 43758.5453));
  const aqiVal = (hash % 160) + 15;
  
  let label: AQIData['label'] = 'Good';
  let color = '#10B981';
  if (aqiVal > 150) {
    label = 'Unhealthy';
    color = '#EF4444';
  } else if (aqiVal > 100) {
    label = 'Unhealthy for Sensitive';
    color = '#F97316';
  } else if (aqiVal > 50) {
    label = 'Moderate';
    color = '#F59E0B';
  }

  const roundedLat = lat.toFixed(4);
  const roundedLng = lng.toFixed(4);

  return {
    id: `dyn-${lat.toFixed(3)}-${lng.toFixed(3)}`,
    title: `Custom Coordinates (${roundedLat}, ${roundedLng})`,
    category: 'aqi',
    lat,
    lng,
    address: `Lat: ${roundedLat}, Lng: ${roundedLng}`,
    city: 'Custom Location',
    region: 'Global Grid',
    country: 'International',
    summary: 'Dynamic environmental assessment generated for selected GPS coordinate point.',
    verified: false,
    updatedAt: new Date().toISOString(),
    aqi: {
      index: aqiVal,
      label,
      pm25: Number((aqiVal * 0.45).toFixed(1)),
      pm10: Number((aqiVal * 0.8).toFixed(1)),
      o3: (hash % 40) + 10,
      no2: (hash % 35) + 5,
      co: Number(((hash % 15) * 0.1).toFixed(1)),
      so2: Number(((hash % 10) * 0.2).toFixed(1)),
      mainPollutant: aqiVal > 80 ? 'PM2.5' : 'O3',
      statusColor: color,
    },
    canopy: {
      coveragePercent: (hash % 60) + 15,
      treeCountEstimate: (hash % 5000) + 500,
      nativeSpecies: ['Local Evergreen', 'Wild Meadow Grass', 'Deciduous Oak'],
      carbonOffsetTonsYear: (hash % 300) + 50,
      heatIslandMitigationScore: (hash % 6) + 4,
    },
  };
}
